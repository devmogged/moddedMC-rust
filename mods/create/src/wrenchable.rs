pub(crate) fn is_wrenchable(block: &str) -> bool {
    BLOCKS.binary_search(&block).is_ok()
        || block.strip_prefix("create:").is_some_and(|path| {
            DYED_SUFFIXES.iter().any(|suffix| {
                path.strip_suffix(suffix)
                    .is_some_and(|dye| DYES.contains(&dye))
            })
        })
}

